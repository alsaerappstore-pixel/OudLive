"""Generate the immutable RT bank from the same catalogue used by Swift UI."""
from pathlib import Path
import json, hashlib, sys
root=Path(__file__).resolve().parents[1]
src=root/'OudLive/RhythmBank/catalogue.json'
rows=json.loads(src.read_text(encoding='utf-8'))
out=['// Generated by scripts/generate-rhythm-patterns.py; do not edit.',
     '// catalogue SHA256: '+hashlib.sha256(src.read_bytes()).hexdigest(),
     '#pragma once','#include <array>','namespace oud {',
     'struct RhythmStep { std::array<float,6> gain; };',
     'struct RhythmPattern { int count; std::array<RhythmStep,128> steps; };',
     'inline constexpr RhythmPattern rhythmPatterns[] = {']
for index,row in enumerate(rows):
    assert row['id']==index
    assert len(row['steps'])==row['numerator']*16//row['denominator']<=128
    assert 40<=row['bpm']<=220
    notes=[]
    for step in row['steps']:
        assert len(step)==6 and all(0<=x<=1 for x in step)
        notes.append('{{'+','.join(f'{float(x):.3f}f' for x in step)+'}}')
    out.append('    {'+str(len(notes))+', {{'+','.join(notes)+'}}},')
out+=['};','inline constexpr int rhythmCount=sizeof(rhythmPatterns)/sizeof(rhythmPatterns[0]);','}']
text='\n'.join(out)+'\n'
target=root/'OudLive/Audio/RhythmPatterns.hpp'
if '--check' in sys.argv:
    assert target.read_text(encoding='utf-8')==text,'Regenerate rhythm header'
    print('PASS catalogue/header agreement:',len(rows),'rhythms')
else: target.write_text(text,encoding='utf-8',newline='\n')
